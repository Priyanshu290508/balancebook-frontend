export function formatProductName(rawName?: string, lang: LanguageCode = "en"): string {
  if (!rawName) return ""
  const isEn = lang === "en" || !["hi", "hinglish"].includes(lang)

  for (const item of Object.values(KNOWN_PRODUCTS)) {
    if (rawName.includes(item.en) || rawName.includes(item.hi)) {
      if (isEn) return item.en
      if (lang === "hi") return item.hi
      if (lang === "hinglish") return item.hinglish || item.en
    }
  }

  const parenMatch = rawName.match(/^([^(]+)\(([^)]+)\)$/)
  if (parenMatch) {
    const hindiPart = parenMatch[1].trim()
    const enPart = parenMatch[2].trim()
    if (isEn) return enPart
    if (lang === "hi") return hindiPart
  }

  if (isEn && /[\u0900-\u097F]/.test(rawName)) {
    const cleanLatin = rawName.replace(/[\u0900-\u097F()]/g, "").trim()
    if (cleanLatin.length > 1) return cleanLatin
  }

  return rawName
}

export function formatCategoryName(rawCat?: string, lang: LanguageCode = "en"): string {
  if (!rawCat) return ""
  const isEn = lang === "en" || !["hi", "hinglish"].includes(lang)

  if (rawCat === "ALL" || rawCat === "All" || rawCat === "सभी") {
    return isEn ? "All" : lang === "hi" ? "सभी" : "All (Sabhi)"
  }

  for (const [key, item] of Object.entries(KNOWN_CATEGORIES)) {
    if (rawCat.includes(key) || rawCat.includes(item.hi) || rawCat.includes(item.en)) {
      if (isEn) return item.en
      if (lang === "hi") return item.hi
      if (lang === "hinglish") return item.hinglish || item.en
    }
  }

  const parenMatch = rawCat.match(/^([^(]+)\(([^)]+)\)$/)
  if (parenMatch) {
    const hindiPart = parenMatch[1].trim()
    const enPart = parenMatch[2].trim()
    if (isEn) return enPart
    if (lang === "hi") return hindiPart
  }

  if (isEn) {
    if (rawCat.includes("मसाले व नमक") || rawCat.includes("मसाले")) return "Spices & Salt"
    if (rawCat.includes("अनाज")) return "Grains"
    if (rawCat.includes("दाल")) return "Pulses"
    if (rawCat.includes("तेल")) return "Cooking Oil"
    if (rawCat.includes("डेयरी")) return "Dairy"
    if (rawCat.includes("किराना")) return "Grocery"
    if (rawCat.includes("स्नैक्स")) return "Snacks"
  }

  return rawCat
}

interface LanguageContextType {
  language: LanguageCode
  isEn: boolean
  setLanguage: (lang: LanguageCode) => void
  t: (key: string, fallback?: string) => string
  formatProductName: (name?: string) => string
  formatCategoryName: (cat?: string) => string
  languages: LanguageInfo[]
  currentLanguageInfo: LanguageInfo
}

const LanguageContext = React.createContext<LanguageContextType | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = React.useState<LanguageCode>("hi")

  React.useEffect(() => {
    try {
      const saved = (localStorage.getItem("balance_book_lang") || localStorage.getItem("dukan_khata_lang")) as LanguageCode | null
      if (saved && TRANSLATIONS[saved]) {
        setLanguageState(saved)
      }
    } catch {}
  }, [])

  const setLanguage = React.useCallback((lang: LanguageCode) => {
    setLanguageState(lang)
    try {
      localStorage.setItem("balance_book_lang", lang)
      document.documentElement.lang = lang
    } catch {}
  }, [])

  const isEn = language === "en" || !["hi", "hinglish"].includes(language)

  const t = React.useCallback(
    (key: string, fallback?: string): string => {
      const currentDict = TRANSLATIONS[language]
      if (currentDict && currentDict[key]) {
        return currentDict[key]
      }
      if (language === "en" || !["hi", "hinglish"].includes(language)) {
        if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key]
        if (fallback && !/[\u0900-\u097F]/.test(fallback)) {
          return fallback
        }
        // If fallback contains Hindi characters, try to strip them or find clean English in parentheses
        if (fallback) {
          const parenMatch = fallback.match(/\(([^)]+)\)/)
          if (parenMatch && !/[\u0900-\u097F]/.test(parenMatch[1])) {
            return parenMatch[1].trim()
          }
          const cleanLatin = fallback.replace(/[\u0900-\u097F()]/g, "").trim()
          if (cleanLatin.length > 0) return cleanLatin
        }
        // Clean fallback from key name: e.g. "product_name" -> "Product Name"
        return key.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase())
      }
      if (language === "hi") {
        return TRANSLATIONS.hi[key] || fallback || key
      }
      if (language === "hinglish") {
        return TRANSLATIONS.hinglish[key] || TRANSLATIONS.en[key] || fallback || key
      }
      return TRANSLATIONS.en[key] || TRANSLATIONS.hi[key] || fallback || key
    },
    [language]
  )

  const formatProd = React.useCallback(
    (name?: string) => formatProductName(name, language),
    [language]
  )

  const formatCat = React.useCallback(
    (cat?: string) => formatCategoryName(cat, language),
    [language]
  )

  const currentLanguageInfo = React.useMemo(() => {
    return (
      SUPPORTED_LANGUAGES.find((l) => l.code === language) ||
      SUPPORTED_LANGUAGES[0]
    )
  }, [language])

  return (
    <LanguageContext.Provider
      value={{
        language,
        isEn,
        setLanguage,
        t,
        formatProductName: formatProd,
        formatCategoryName: formatCat,
        languages: SUPPORTED_LANGUAGES,
        currentLanguageInfo,
      }}
    >
      {children}
    </LanguageContext.Provider>
  )
}

export function useTranslation() {
  const context = React.useContext(LanguageContext)
  if (!context) {
    throw new Error("useTranslation must be used within LanguageProvider")
  }
  return context
}
